/** 카드 수에 맞춘 MAGO_v2 v7 Strict JSON 출력 스키마입니다. */
export function buildMagoTarotReadingResponseSchema(cardCount: number) {
  return {
    type: "object",
    properties: {
      res_score: {
        type: "integer",
        minimum: 0,
        maximum: 100,
      },
      res_score_status: {
        type: "string",
        enum: ["매우 긍정", "안정/정체", "조율 필요"],
      },
      res_theme: { type: "string" },
      res_readings: {
        type: "array",
        minItems: cardCount,
        maxItems: cardCount,
        items: {
          type: "object",
          properties: {
            label: { type: "string" },
            card_name_en: { type: "string" },
            is_reversed: { type: "boolean" },
            one_liner: { type: "string" },
            paragraphs: {
              type: "array",
              minItems: 2,
              maxItems: 2,
              items: { type: "string" },
            },
          },
          required: [
            "label",
            "card_name_en",
            "is_reversed",
            "one_liner",
            "paragraphs",
          ],
          additionalProperties: false,
        },
      },
      res_mago_advice: {
        type: "object",
        properties: {
          summary: { type: "string" },
        },
        required: ["summary"],
        additionalProperties: false,
      },
    },
    required: [
      "res_score",
      "res_score_status",
      "res_theme",
      "res_readings",
      "res_mago_advice",
    ],
    additionalProperties: false,
  } as const;
}
